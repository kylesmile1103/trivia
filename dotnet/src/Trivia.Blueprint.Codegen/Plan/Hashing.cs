using System.Security.Cryptography;
using System.Text;

namespace Trivia.Blueprint.Codegen.Plan;

internal static class Hashing
{
    private const string Marker = "// <auto-generated>\n//   trivia-dotnet ";
    private const string BodyHashMarker = "//   body-sha256: ";
    private const string HeaderEnd = "\n// </auto-generated>\n";

    internal static string Generator { get; } = typeof(Hashing).Assembly.GetName().Version!.ToString(3);
    internal static string Of(ReadOnlySpan<byte> bytes) => "sha256:" + Hex(bytes);

    internal static byte[] Generated(string content)
    {
        string text = "#nullable enable\n" + content.TrimEnd('\n') + "\n";
        byte[] body = Encoding.UTF8.GetBytes(text);
        string header = Marker + Generator + ". This file is overwritten on every run.\n" +
                        "//   Put your code in the partial type beside it.\n" +
                        BodyHashMarker + Hex(body) + HeaderEnd;
        return [.. Encoding.UTF8.GetBytes(header), .. body];
    }

    internal static bool IsOwned(ReadOnlySpan<byte> bytes) => bytes.StartsWith(Encoding.ASCII.GetBytes(Marker));

    internal static bool HasValidBody(ReadOnlySpan<byte> bytes)
    {
        if (!IsOwned(bytes))
            return false;
        int headerEnd = bytes.IndexOf(Encoding.ASCII.GetBytes(HeaderEnd));
        if (headerEnd < 0)
            return false;
        ReadOnlySpan<byte> hashLine = bytes[..headerEnd];
        int hashStart = hashLine.LastIndexOf(Encoding.ASCII.GetBytes(BodyHashMarker));
        return hashStart >= 0 && Encoding.ASCII.GetString(hashLine[(hashStart + BodyHashMarker.Length)..]) ==
            Hex(bytes[(headerEnd + HeaderEnd.Length)..]);
    }

    private static string Hex(ReadOnlySpan<byte> bytes) => Convert.ToHexStringLower(SHA256.HashData(bytes));
}
