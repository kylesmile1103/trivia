// Reads what hey-api actually generated, with the TypeScript parser (no type checker needed).
// The manifest's function and type names come from here — never from re-deriving hey-api's
// naming rules, which depend on operation order (duplicate ids get numeric suffixes) and config.

import fs from 'node:fs'
import path from 'node:path'

import ts from 'typescript'

import { ContractSyncError } from '../errors.js'

export const GENERATED_FILES = {
  queries: '@tanstack/react-query.gen.ts',
  sdk: 'sdk.gen.ts',
  types: 'types.gen.ts',
  client: 'client.gen.ts',
  index: 'index.ts',
} as const

export const HEY_API_HEADER = '// This file is auto-generated by @hey-api/openapi-ts'

export interface SdkFunction {
  name: string
  /** Upper-case HTTP method of the client call, e.g. "GET". */
  method: string
  /** The `url` template passed to the client, e.g. "/api/v1/customers/{id}". */
  url: string
  /** First type argument of the `RequestResult<…>` return type, e.g. "GetCustomerByIdResponses". */
  responsesType: string | null
  /** Type argument of the `Options<…>` parameter, e.g. "GetCustomerByIdData". */
  dataType: string | null
}

export type QueryFactory = 'queryOptions' | 'infiniteQueryOptions' | 'mutationOptions' | 'queryKey' | 'infiniteQueryKey'

export interface QueryExport {
  name: string
  factory: QueryFactory | null
  /** SDK functions called from the initializer. */
  sdkCalls: string[]
  /** Other exports of the same file called from the initializer (e.g. the query key factory). */
  localCalls: string[]
}

export interface OperationFunctions {
  sdkFn: string
  queryOptionsFn: string | null
  queryKeyFn: string | null
  infiniteQueryOptionsFn: string | null
  infiniteQueryKeyFn: string | null
  mutationFn: string | null
}

export interface GeneratedCode {
  dir: string
  sdkFunctions: ReadonlyMap<string, SdkFunction>
  queryExports: ReadonlyMap<string, QueryExport>
  /** Exported type aliases / interfaces of types.gen.ts by name. */
  types: ReadonlyMap<string, ts.TypeNode | null>
  /** Look up the SDK function for `METHOD path`; undefined when hey-api generated none. */
  sdkFor(method: string, url: string): SdkFunction | undefined
  /** Functions generated for one SDK function; fails loudly on ambiguity. */
  functionsFor(sdkFn: string): OperationFunctions
  /** Every query/mutation export that maps to some SDK function. */
  hookExports(): ReadonlySet<string>
}

const HTTP_CALLS = new Set(['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'])

function parse(file: string): ts.SourceFile {
  let text: string
  try {
    text = fs.readFileSync(file, 'utf8')
  } catch (cause) {
    throw new ContractSyncError('reconcile_failed', `Generated file ${file} is missing or unreadable`, { cause })
  }
  return ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
}

function isExported(node: ts.Node): boolean {
  return (
    ts.canHaveModifiers(node) &&
    (ts.getModifiers(node) ?? []).some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
  )
}

function exportedConsts(source: ts.SourceFile): Array<{ name: string; initializer: ts.Expression }> {
  const result: Array<{ name: string; initializer: ts.Expression }> = []
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement) || !isExported(statement)) continue
    for (const declaration of statement.declarationList.declarations) {
      if (ts.isIdentifier(declaration.name) && declaration.initializer) {
        result.push({ name: declaration.name.text, initializer: declaration.initializer })
      }
    }
  }
  return result
}

function forEachDescendant(node: ts.Node, visit: (node: ts.Node) => void): void {
  const walk = (child: ts.Node): void => {
    visit(child)
    ts.forEachChild(child, walk)
  }
  ts.forEachChild(node, walk)
}

function typeReferenceName(node: ts.TypeNode | undefined): string | null {
  if (node && ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)) return node.typeName.text
  return null
}

function readSdk(file: string): Map<string, SdkFunction> {
  const source = parse(file)
  const functions = new Map<string, SdkFunction>()
  for (const { name, initializer } of exportedConsts(source)) {
    if (!ts.isArrowFunction(initializer)) continue
    const calls: Array<{ method: string; url: string }> = []
    forEachDescendant(initializer, (node) => {
      if (!ts.isCallExpression(node) || !ts.isPropertyAccessExpression(node.expression)) return
      const method = node.expression.name.text
      const config = node.arguments[0]
      if (!HTTP_CALLS.has(method) || !config || !ts.isObjectLiteralExpression(config)) return
      for (const property of config.properties) {
        if (
          ts.isPropertyAssignment(property) &&
          ts.isIdentifier(property.name) &&
          property.name.text === 'url' &&
          ts.isStringLiteralLike(property.initializer)
        ) {
          calls.push({ method: method.toUpperCase(), url: property.initializer.text })
        }
      }
    })
    if (calls.length === 0) continue
    const [call] = calls
    if (calls.length > 1 || call === undefined) {
      throw new ContractSyncError(
        'reconcile_failed',
        `${file}: SDK function ${name} makes ${calls.length} client calls; expected exactly one`,
      )
    }
    const returnType = initializer.type
    const responsesType =
      returnType && ts.isTypeReferenceNode(returnType) ? typeReferenceName(returnType.typeArguments?.[0]) : null
    const optionsType = initializer.parameters[0]?.type
    const dataType =
      optionsType && ts.isTypeReferenceNode(optionsType) ? typeReferenceName(optionsType.typeArguments?.[0]) : null
    functions.set(name, { name, ...call, responsesType, dataType })
  }
  return functions
}

function readQueries(file: string, sdkNames: ReadonlySet<string>): Map<string, QueryExport> {
  const source = parse(file)
  // Value imports by local name → module specifier (type-only imports can't be called).
  const imports = new Map<string, string>()
  for (const statement of source.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier)) continue
    const clause = statement.importClause
    if (!clause || clause.isTypeOnly) continue
    const bindings = clause.namedBindings
    if (bindings && ts.isNamedImports(bindings)) {
      for (const element of bindings.elements) {
        if (!element.isTypeOnly) imports.set(element.name.text, statement.moduleSpecifier.text)
      }
    }
  }
  const isSdkImport = (name: string): boolean => /(^|\/)sdk\.gen$/.test(imports.get(name) ?? '') && sdkNames.has(name)
  const isTanstack = (name: string, expected: string): boolean =>
    name === expected && imports.get(name) === '@tanstack/react-query'

  const consts = exportedConsts(source)
  const exportNames = new Set(consts.map((entry) => entry.name))
  const result = new Map<string, QueryExport>()
  for (const { name, initializer } of consts) {
    const sdkCalls = new Set<string>()
    const localCalls = new Set<string>()
    const seen: { factory: QueryFactory | null; mutationFn: boolean } = { factory: null, mutationFn: false }
    forEachDescendant(initializer, (node) => {
      if (ts.isPropertyAssignment(node) && ts.isIdentifier(node.name) && node.name.text === 'mutationFn') {
        seen.mutationFn = true
      }
      if (!ts.isCallExpression(node) || !ts.isIdentifier(node.expression)) return
      const callee = node.expression.text
      if (isSdkImport(callee)) sdkCalls.add(callee)
      else if (exportNames.has(callee) && callee !== name) localCalls.add(callee)
      else if (isTanstack(callee, 'queryOptions')) seen.factory = 'queryOptions'
      else if (isTanstack(callee, 'infiniteQueryOptions')) seen.factory = 'infiniteQueryOptions'
      else if (callee === 'createQueryKey' && !imports.has(callee)) {
        // hey-api's local helper: createQueryKey(id, options, infinite?)
        const infinite = node.arguments[2]?.kind === ts.SyntaxKind.TrueKeyword
        seen.factory ??= infinite ? 'infiniteQueryKey' : 'queryKey'
      }
    })
    const factory = seen.factory ?? (seen.mutationFn ? 'mutationOptions' : null)
    result.set(name, { name, factory, sdkCalls: [...sdkCalls].sort(), localCalls: [...localCalls].sort() })
  }
  return result
}

function readTypes(file: string): Map<string, ts.TypeNode | null> {
  const source = parse(file)
  const types = new Map<string, ts.TypeNode | null>()
  for (const statement of source.statements) {
    if (ts.isTypeAliasDeclaration(statement) && isExported(statement)) types.set(statement.name.text, statement.type)
    else if (ts.isInterfaceDeclaration(statement) && isExported(statement)) types.set(statement.name.text, null)
  }
  return types
}

export function readGeneratedCode(dir: string): GeneratedCode {
  const sdkFunctions = readSdk(path.join(dir, GENERATED_FILES.sdk))
  const queryExports = readQueries(path.join(dir, GENERATED_FILES.queries), new Set(sdkFunctions.keys()))
  const types = readTypes(path.join(dir, GENERATED_FILES.types))

  const byRoute = new Map<string, SdkFunction>()
  for (const fn of sdkFunctions.values()) {
    const key = `${fn.method} ${fn.url}`
    const existing = byRoute.get(key)
    if (existing) {
      throw new ContractSyncError(
        'reconcile_failed',
        `Both ${existing.name} and ${fn.name} in ${GENERATED_FILES.sdk} call ${key}`,
      )
    }
    byRoute.set(key, fn)
  }

  const unique = (sdkFn: string, factory: QueryFactory, candidates: readonly QueryExport[]): string | null => {
    const matches = candidates.filter((entry) => entry.factory === factory)
    if (matches.length > 1) {
      throw new ContractSyncError(
        'reconcile_failed',
        `${GENERATED_FILES.queries} exports several ${factory} factories for ${sdkFn}: ${matches.map((m) => m.name).join(', ')}`,
      )
    }
    return matches[0]?.name ?? null
  }

  const functionsFor = (sdkFn: string): OperationFunctions => {
    const callers = [...queryExports.values()].filter(
      (entry) => entry.sdkCalls.length === 1 && entry.sdkCalls[0] === sdkFn,
    )
    const keyOf = (optionsFn: string | null, factory: QueryFactory): string | null => {
      if (optionsFn === null) return null
      const owner = queryExports.get(optionsFn)
      const keys = (owner?.localCalls ?? [])
        .map((local) => queryExports.get(local))
        .filter((entry): entry is QueryExport => entry?.factory === factory)
      if (keys.length !== 1) {
        throw new ContractSyncError(
          'reconcile_failed',
          `${optionsFn} in ${GENERATED_FILES.queries} uses ${keys.length} ${factory} factories; expected exactly one`,
        )
      }
      return keys[0]?.name ?? null
    }
    const queryOptionsFn = unique(sdkFn, 'queryOptions', callers)
    const infiniteQueryOptionsFn = unique(sdkFn, 'infiniteQueryOptions', callers)
    return {
      sdkFn,
      queryOptionsFn,
      queryKeyFn: keyOf(queryOptionsFn, 'queryKey'),
      infiniteQueryOptionsFn,
      infiniteQueryKeyFn: keyOf(infiniteQueryOptionsFn, 'infiniteQueryKey'),
      mutationFn: unique(sdkFn, 'mutationOptions', callers),
    }
  }

  // Every export that is one of the five factory kinds; the manifest must account for all of them.
  const hookExports = (): ReadonlySet<string> =>
    new Set([...queryExports.values()].filter((entry) => entry.factory !== null).map((entry) => entry.name))

  return {
    dir,
    sdkFunctions,
    queryExports,
    types,
    sdkFor: (method, url) => byRoute.get(`${method.toUpperCase()} ${url}`),
    functionsFor,
    hookExports,
  }
}

// ---- Type navigation over types.gen.ts (syntactic; hey-api prints simple shapes) ----

function stripNull(node: ts.TypeNode): ts.TypeNode {
  if (ts.isParenthesizedTypeNode(node)) return stripNull(node.type)
  if (ts.isUnionTypeNode(node)) {
    const rest = node.types.filter(
      (member) =>
        !(ts.isLiteralTypeNode(member) && member.literal.kind === ts.SyntaxKind.NullKeyword) &&
        member.kind !== ts.SyntaxKind.UndefinedKeyword,
    )
    if (rest.length === 1 && rest[0] !== undefined) return stripNull(rest[0])
  }
  return node
}

function propertyName(name: ts.PropertyName): string | null {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) return name.text
  return null
}

/**
 * Member type of an object type: a type literal, an alias of one, or an intersection of those
 * (hey-api prints `allOf` as `A & { … }`). Alias hops are bounded, so recursive types are safe.
 */
export function memberType(code: GeneratedCode, node: ts.TypeNode, member: string, depth = 0): ts.TypeNode | null {
  if (depth > 16) return null
  let target = stripNull(node)
  const alias = typeReferenceName(target)
  if (alias !== null && code.types.get(alias)) target = stripNull(code.types.get(alias) as ts.TypeNode)
  if (ts.isIntersectionTypeNode(target)) {
    for (const part of target.types) {
      const found = memberType(code, part, member, depth + 1)
      if (found !== null) return found
    }
    return null
  }
  if (!ts.isTypeLiteralNode(target)) return null
  for (const element of target.members) {
    if (ts.isPropertySignature(element) && element.type && propertyName(element.name) === member) {
      return element.type
    }
  }
  return null
}

/** Element type of `Array<X>` / `X[]` (after null-stripping and one alias hop), else null. */
export function arrayElement(code: GeneratedCode, node: ts.TypeNode): ts.TypeNode | null {
  let target = stripNull(node)
  const alias = typeReferenceName(target)
  if (alias !== null && alias !== 'Array' && code.types.get(alias)) {
    target = stripNull(code.types.get(alias) as ts.TypeNode)
  }
  if (ts.isArrayTypeNode(target)) return target.elementType
  if (ts.isTypeReferenceNode(target) && typeReferenceName(target) === 'Array') return target.typeArguments?.[0] ?? null
  return null
}

/** Name of an exported types.gen.ts type the node refers to, else null. */
export function namedType(code: GeneratedCode, node: ts.TypeNode | null): string | null {
  if (node === null) return null
  const name = typeReferenceName(stripNull(node))
  return name !== null && name !== 'Array' && code.types.has(name) ? name : null
}

/** `XResponses[status]` from types.gen.ts. */
export function responseType(code: GeneratedCode, fn: SdkFunction, status: string): ts.TypeNode | null {
  if (fn.responsesType === null) return null
  const responses = code.types.get(fn.responsesType)
  return responses ? memberType(code, responses, status) : null
}

/** The 2xx status keys of `XResponses` (the members of the `XResponse` union hooks return). */
export function successStatuses(code: GeneratedCode, fn: SdkFunction): string[] {
  const responses = fn.responsesType === null ? undefined : code.types.get(fn.responsesType)
  if (!responses || !ts.isTypeLiteralNode(responses)) return []
  return responses.members
    .map((member) => (ts.isPropertySignature(member) ? propertyName(member.name) : null))
    .filter((name): name is string => name !== null && /^2(\d\d|XX)$/.test(name))
}

/** `XData['body']` from types.gen.ts. */
export function bodyType(code: GeneratedCode, fn: SdkFunction): ts.TypeNode | null {
  if (fn.dataType === null) return null
  const data = code.types.get(fn.dataType)
  return data ? memberType(code, data, 'body') : null
}

/** Every module specifier a generated file imports or re-exports (static and dynamic). */
export function importSpecifiers(text: string): string[] {
  return ts.preProcessFile(text, true, true).importedFiles.map((entry) => entry.fileName)
}
