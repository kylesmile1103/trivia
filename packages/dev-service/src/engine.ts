// The native engine (`@trivia/engine`, built from crates/trivia_napi). It is loaded when the
// dev server resolves its config, so a missing native build stops `vite` with the fix instead
// of breaking `vite build`, which never runs this plugin.

import type { Envelope, ErrorCode, FileChange } from './types.js'

/** A `data-ast-node` insertion. `offset` is in UTF-16 code units (a JavaScript string index). */
export interface Insertion {
  offset: number
  text: string
}

/** `applyOps` data: the last op's file and locator, plus every file's net change. */
export interface OpsResult {
  file: string
  changed: boolean
  locator: string | null
  changes: FileChange[]
}

/**
 * A guarded write for `restoreFiles`: replace `file` with `content` only if it equals
 * `expected`. `expected: null`: the file must not exist (it is created); `content: null`: delete it.
 */
export interface GuardedWrite {
  file: string
  expected: string | null
  content: string | null
}

/** The part of the binding this plugin uses. Everything but `annotate` returns a JSON envelope. */
export interface EngineBinding {
  /** Throws (message `cannot parse …`) when `code` has a syntax error. */
  analyzeExpressions(requestJson: string): string
  renameReferences(requestJson: string): string
  annotate(code: string, file: string): Insertion[]
  applyOps(root: string, opsJson: string): string
  inspect(root: string, locator: string): string
  outline(root: string, file: string): string
  describeValues(root: string, file: string): string
  describeValue(root: string, path: string): string
  mentions(root: string, file: string, name: string): string
  components(root: string, uiDir: string, importBase: string): string
  restoreFiles(root: string, writesJson: string): string
}

const REQUIRED = ['annotate', 'applyOps', 'inspect', 'outline', 'describeValues', 'describeValue', 'mentions', 'components', 'restoreFiles', 'analyzeExpressions', 'renameReferences'] as const

// Not a literal, so type-checking does not depend on the native build (the binding's
// index.d.ts is generated by `pnpm build:engine`); the shape is verified at load time instead.
const ENGINE_MODULE: string = '@trivia/engine'

export async function loadEngine(): Promise<EngineBinding> {
  let mod: Record<string, unknown>
  try {
    mod = (await import(ENGINE_MODULE)) as Record<string, unknown>
  } catch (cause) {
    throw new Error(
      `[trivia] cannot load the native engine (${ENGINE_MODULE}); build it with \`pnpm build:engine\` ` +
        `at the workspace root. Cause: ${cause instanceof Error ? cause.message : String(cause)}`,
      { cause },
    )
  }
  const missing = REQUIRED.filter((name) => typeof mod[name] !== 'function')
  if (missing.length > 0) {
    throw new Error(
      `[trivia] ${ENGINE_MODULE} does not export ${missing.join(', ')}; it is stale, rebuild it with \`pnpm build:engine\``,
    )
  }
  return mod as unknown as EngineBinding
}

/** A failure with an API error code; the HTTP status is derived from the code. */
export class ApiError extends Error {
  readonly code: ErrorCode

  constructor(code: ErrorCode, message: string, readonly details?: Record<string, unknown>) {
    super(message)
    this.name = 'ApiError'
    this.code = code
  }
}

/** Data of a binding envelope, or its error thrown as an `ApiError`. */
export function unwrap<T>(json: string): T {
  let envelope: Envelope<T>
  try {
    envelope = JSON.parse(json) as Envelope<T>
  } catch {
    throw new ApiError('internal', `the engine returned non-JSON: ${json.slice(0, 200)}`)
  }
  if (!envelope.ok) throw new ApiError(envelope.error.code, envelope.error.message, envelope.error.details)
  return envelope.data
}
